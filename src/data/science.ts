import { type Q, type Subject, ri, pick, mkQ } from './types';

const genCalc = (): Q => {
  const t = ri(0, 3);
  if (t === 0) {
    const v = pick([2, 3, 4, 5, 10, 15, 20]), s = pick([2, 4, 5, 8, 10]);
    return mkQ(`${v * s}m を ${s} 秒で移動した物体の平均の速さは？`, `${v}m/s`, [`${v * s * s}m/s`, `${v * 2}m/s`, `${s}m/s`].filter(x => x !== `${v}m/s`), `速さ = 距離 ÷ 時間 = ${v * s} ÷ ${s}`, () => `${ri(1, 30)}m/s`);
  }
  if (t === 1) {
    const N = pick([2, 5, 10, 20, 30, 50]), m = pick([0.5, 1, 2, 3, 4]);
    const J = N * m;
    return mkQ(`${N}N の力で物体を力の向きに ${m}m 動かしたときの仕事は？`, `${J}J`, [`${J * 2}J`, `${N + m}J`, `${J * 10}J`], `仕事[J] = 力[N] × 力の向きに動いた距離[m]`, () => `${ri(1, 100)}J`);
  }
  if (t === 2) {
    const W = pick([2, 5, 10, 20, 25]), s = pick([2, 4, 5, 10]);
    return mkQ(`${W * s}J の仕事を ${s} 秒間でしたときの仕事率は？`, `${W}W`, [`${W * s * s}W`, `${W * s + s}W`, `${s}W`].filter(x => x !== `${W}W`), `仕事率[W] = 仕事[J] ÷ 時間[s]`, () => `${ri(1, 60)}W`);
  }
  const g = pick([100, 200, 300, 500, 1000, 2000]), h = pick([1, 2, 3, 0.5]);
  const N = g / 100;
  return mkQ(`質量 ${g}g の物体を ${h}m の高さまでゆっくり持ち上げる仕事は？（100g の物体にはたらく重力を 1N とする）`, `${N * h}J`, [`${g * h}J`, `${N}J`, `${N * h * 10}J`], `${g}g → ${N}N、${N}N × ${h}m`, () => `${ri(1, 30)}J`);
};

